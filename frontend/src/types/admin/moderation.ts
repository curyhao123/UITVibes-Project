// ─── AI Moderation — types for the admin content-review screen ─────────────────

/**
 * Moderation status. Matches the ModerationStatus enum on the backend:
 * 0=Pending, 1=Approved, 2=Rejected, 3=NeedsReview
 *
 * Note: the backend serializes enums with JsonStringEnumConverter, so values
 * arrive as strings ("Approved"), not numbers. We use strings to stay safe.
 */
export type ModerationStatus = "Pending" | "Approved" | "Rejected" | "NeedsReview";

/** The kind of content that was moderated. */
export type ModerationTargetType = "Post" | "Comment" | "Reel" | "Story";

/**
 * Where the decision came from:
 *  - Rule     = automatic rule (e.g. an empty post is auto-approved)
 *  - Llm      = decided by the AI
 *  - Fallback = the AI failed / was unavailable → routed to NeedsReview
 */
export type ModerationSource = "Rule" | "Llm" | "Fallback";

/** A moderation record returned by GET /post/moderation. */
export interface BE_ModerationResult {
  id: string;
  targetId: string;
  targetType: ModerationTargetType;
  status: ModerationStatus;
  source: ModerationSource;

  /** The AI's raw decision: "approve" | "reject" | "review". */
  llmDecision: string | null;
  /** Severity level 0–3. */
  severity: number | null;
  /** Confidence 0.0–1.0. */
  confidence: number | null;
  /** Violation categories, e.g. ["harassment", "spam"]. */
  categories: string[];

  /** The reason shown to the author (generated by the AI). */
  authorReason: string | null;
  /** Internal code for debugging, e.g. "llm_approve", "llm_unavailable:timeout". */
  internalReasonCode: string;

  attemptCount: number;
  createdAt: string;
  updatedAt: string;

  /** Note left by the admin when resolving the item. */
  adminNote: string | null;
  reviewedBy: string | null;
  reviewedAt: string | null;

  /** The moderated content. */
  targetContent: string;
  targetMediaUrls: string[];
  /** True when the author deleted the content before it could be reviewed. */
  targetDeleted: boolean;

  /** Author info. */
  authorId: string;
  authorDisplayName: string;
  authorAvatarUrl: string;
}

/** Aggregate stats from GET /post/moderation/stats. */
export interface BE_ModerationStats {
  total: number;
  pending: number;
  approved: number;
  rejected: number;
  needsReview: number;
  fallbackCount: number;
  reviewedByAdminCount: number;
  /** Records whose original content was deleted by the author. */
  orphanCount: number;
}

/** Filters for the moderation queue. */
export interface ModerationQueryParams {
  status?: ModerationStatus;
  targetType?: ModerationTargetType;
  category?: string;
  orderByUpdatedAt?: boolean;
  skip?: number;
  take?: number;
}